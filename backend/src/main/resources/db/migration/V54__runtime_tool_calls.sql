CREATE TABLE runtime_tool_calls (
    id BIGINT PRIMARY KEY AUTO_INCREMENT,
    instance_key VARCHAR(128) NOT NULL,
    call_id VARCHAR(36) NOT NULL,
    generation VARCHAR(36) NOT NULL,
    agent_id BIGINT NOT NULL,
    endpoint_key VARCHAR(128) NOT NULL,
    tool_name VARCHAR(96) NOT NULL,
    tool_kind VARCHAR(16) NOT NULL,
    trace_id VARCHAR(32) NOT NULL,
    fingerprint VARCHAR(64) NOT NULL,
    decision_key VARCHAR(128) NOT NULL,
    safety_decision VARCHAR(16) NOT NULL,
    data_action VARCHAR(32) NOT NULL,
    reason_code VARCHAR(128) NOT NULL,
    state VARCHAR(24) NOT NULL,
    created_at TIMESTAMP(6) NOT NULL,
    expires_at TIMESTAMP(6) NOT NULL,
    claimed_at TIMESTAMP(6) NULL,
    completed_at TIMESTAMP(6) NULL,
    duration_ms BIGINT NULL,
    output_digest VARCHAR(64),
    UNIQUE KEY uk_runtime_tool_call (instance_key,call_id),
    KEY idx_runtime_tool_history (instance_key,created_at)
);
