create table management_value_connectors (
    id bigint not null auto_increment,
    connector_key varchar(128) not null,
    name varchar(256) not null,
    system_type varchar(64) not null,
    source_system varchar(128) not null,
    endpoint_url varchar(2048) not null,
    enabled boolean not null default true,
    sync_interval_minutes int not null default 60,
    auth_type varchar(32) not null default 'NONE',
    credential_env_key varchar(128),
    auth_header varchar(128),
    auth_prefix varchar(64),
    records_path varchar(256),
    record_key_path varchar(256) not null,
    observed_at_path varchar(256),
    value_type_path varchar(256),
    fixed_value_type varchar(128) not null default 'OTHER',
    description_path varchar(256),
    benefit_money_path varchar(256) not null,
    currency_path varchar(256),
    fixed_currency varchar(16) not null default 'USD',
    metric_name_path varchar(256),
    fixed_metric_name varchar(128),
    metric_unit_path varchar(256),
    fixed_metric_unit varchar(32),
    baseline_value_path varchar(256),
    current_value_path varchar(256),
    improvement_direction varchar(32) not null default 'HIGHER_IS_BETTER',
    agent_id_path varchar(256),
    default_agent_id bigint,
    endpoint_key_path varchar(256),
    default_endpoint_key varchar(128),
    validated_by varchar(128) not null,
    confidence decimal(5, 4) not null default 0.9000,
    measurement_window_start_path varchar(256),
    measurement_window_end_path varchar(256),
    incremental_parameter varchar(128),
    max_records int not null default 500,
    status varchar(32) not null default 'NEVER_SYNCED',
    last_sync_started_at timestamp(6),
    last_sync_completed_at timestamp(6),
    last_success_at timestamp(6),
    last_imported_count int not null default 0,
    last_skipped_count int not null default 0,
    last_error varchar(1024),
    created_at timestamp(6) not null,
    updated_at timestamp(6) not null,
    primary key (id),
    unique key uk_management_value_connectors_key (connector_key),
    constraint fk_management_value_connector_agent foreign key (default_agent_id) references agents(id)
);

create index idx_management_value_connectors_schedule
    on management_value_connectors(enabled, status, last_sync_completed_at);
